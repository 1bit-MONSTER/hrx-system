"""Regenerate the HIP passthrough coverage artifacts.

The interceptor library (libhip_intercept.so) must export every symbol that
libamdhip64.so exports, with the same symbol-version nodes, otherwise an
application linked against a versioned HIP symbol cannot be intercepted.

This script is the single source of truth for that surface. It reads an actual
libamdhip64.so export table, emits forwarders for every entry point that
hip_intercept.c does not already define, and emits the linker version script
whose node set must match libhrx/src/binding/hip/amdhip64.map. Both are checked:
the script exits non-zero if a node is missing, if a node is extra, or if any
reference symbol would be left without a forwarder.

Usage (from the repository root, after building the HIP binding):

    python3 libhrx/src/passthrough/generate_stubs.py \\
        --reference-lib build/libhrx/src/binding/hip/libamdhip64.so

Wire it into a build by pointing the interceptor at the generated files:
libhrx/src/passthrough/stubs_generated.c and
libhrx/src/passthrough/passthrough_full.map."""

import argparse
import difflib
import os
import re
import subprocess
import sys
from collections import OrderedDict, defaultdict

PASSTHROUGH_DIR = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(PASSTHROUGH_DIR)))
BINDING_DIR = os.path.join(REPO_ROOT, "libhrx", "src", "binding", "hip")
AMD_MAP = os.path.join(BINDING_DIR, "amdhip64.map")

C_OUT = os.path.join(PASSTHROUGH_DIR, "stubs_generated.c")
MAP_OUT = os.path.join(PASSTHROUGH_DIR, "passthrough_full.map")

# Exported by hip_intercept.c itself (not HIP API entry points from the
# reference library) but still part of the interceptor's ABI.
INTERCEPTOR_EXPORTS = [
    "hip_passthrough_backend_lib",
    "hip_passthrough_get_active_table",
    "hip_passthrough_get_real_table",
    "hip_passthrough_log_call",
]

# C keywords and type specifiers that must never be mistaken for a parameter
# name when a prototype leaves a parameter unnamed.
TYPE_WORDS = {
    "auto", "bool", "char", "const", "double", "enum", "extern", "float",
    "inline", "int", "long", "register", "restrict", "short", "signed",
    "static", "struct", "typedef", "union", "unsigned", "void", "volatile",
    "_Bool",
}

