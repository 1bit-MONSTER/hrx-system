"""Regenerate the HIP passthrough coverage artifacts.

The interceptor library (libhip_intercept.so) must export every symbol that
libamdhip64.so exports, with the same symbol-version nodes, otherwise an
application linked against a versioned HIP symbol cannot be intercepted.

This script is the single source of truth for that surface. It reads an actual
libamdhip64.so export table, emits forwarders for every entry point that
hip_intercept.c does not already define, and emits the linker version script
whose node set must match libhrx/src/binding/hip/amdhip64.map. Both are checked:
the script exits non-zero if a node is missing, if a node is extra, or if any
reference symbol would be left without a forwarder.

Usage (from the repository root, after building the HIP binding):

    python3 libhrx/src/passthrough/generate_stubs.py \\
        --reference-lib build/libhrx/src/binding/hip/libamdhip64.so

Wire it into a build by pointing the interceptor at the generated files:
libhrx/src/passthrough/stubs_generated.c and
libhrx/src/passthrough/passthrough_full.map."""

import argparse
import os
import re
import subprocess
import sys
from collections import OrderedDict, defaultdict

PASSTHROUGH_DIR = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(PASSTHROUGH_DIR)))
BINDING_DIR = os.path.join(REPO_ROOT, "libhrx", "src", "binding", "hip")
AMD_MAP = os.path.join(BINDING_DIR, "amdhip64.map")

C_OUT = os.path.join(PASSTHROUGH_DIR, "stubs_generated.c")
MAP_OUT = os.path.join(PASSTHROUGH_DIR, "passthrough_full.map")

# Exported by hip_intercept.c itself (not HIP API entry points from the
# reference library) but still part of the interceptor's ABI.
INTERCEPTOR_EXPORTS = [
    "hip_passthrough_backend_lib",
    "hip_passthrough_get_active_table",
    "hip_passthrough_get_real_table",
    "hip_passthrough_log_call",
]

# C keywords and type specifiers that must never be mistaken for a parameter
# name when a prototype leaves a parameter unnamed.
TYPE_WORDS = {
    "auto", "bool", "char", "const", "double", "enum", "extern", "float",
    "inline", "int", "long", "register", "restrict", "short", "signed",
    "static", "struct", "typedef", "union", "unsigned", "void", "volatile",
    "_Bool",
}

HEADER = """\
// Copyright 2026 The IREE Authors
//
// Licensed under the Apache License v2.0 with LLVM Exceptions.
// See https://llvm.org/LICENSE.txt for license information.
// SPDX-License-Identifier: Apache-2.0 WITH LLVM-exception

//===----------------------------------------------------------------------===//
// AUTO-GENERATED by libhrx/src/passthrough/generate_stubs.py -- DO NOT EDIT.
//
// Forwarders for the %(count)d libamdhip64.so entry points that
// hip_intercept.c does not already provide. Every one of them is exported with
// the same symbol-version node as the reference library so an LD_PRELOADed
// interceptor sees versioned calls too.
//
// Regenerate with:
//   python3 libhrx/src/passthrough/generate_stubs.py \\
//       --reference-lib <build>/libhrx/src/binding/hip/libamdhip64.so
//
// The generator fails if the produced version-node set differs from
// libhrx/src/binding/hip/amdhip64.map or if a reference symbol has no
// forwarder, so the next HIP version node cannot silently reopen the gap.
//===----------------------------------------------------------------------===//

#define _GNU_SOURCE
#include <dlfcn.h>

#include "libhrx/src/binding/hip/api.h"

// hip_intercept.c owns the backend handle and the logging plumbing.
extern void* hip_passthrough_backend_lib(void);
extern void hip_passthrough_log_call(const char* name);

// Type declarations for ABI entry points that api.h does not describe,
// extracted verbatim from libhrx/src/binding/hip/abi_stubs.c.

%(compat)s
"""

# Marks the start of the local compatibility declaration block in abi_stubs.c.
COMPAT_MARKER = "// Local compatibility declarations"


def read_exports(reference_lib):
    """Returns {symbol: version_node} for the reference library's exports."""
    output = subprocess.check_output(
        ["nm", "-D", "--defined-only", reference_lib], text=True
    )
    exports = OrderedDict()
    data_symbols = []
    for line in output.splitlines():
        fields = line.split()
        if len(fields) < 3:
            continue
        kind = fields[1]
        symbol = fields[2]
        if "@" not in symbol:
            continue
        name, _, node = symbol.partition("@@")
        if not node:
            continue
        if kind not in ("T", "W", "i"):
            # Data/absolute symbols have no callable forwarder. Only the
            # version-node sentinels (kind "A") are expected here.
            if kind != "A":
                data_symbols.append(symbol)
            continue
        exports[name] = node
    if data_symbols:
        sys.exit(
            "error: reference library exports data symbols with no forwarder: "
            + ", ".join(sorted(data_symbols))
        )
    return exports


def read_map_nodes(path):
    """Returns the ordered list of version nodes declared in a version script."""
    nodes = []
    with open(path) as f:
        for line in f:
            match = re.match(r"^([A-Za-z_][\w.]*)\s*\{", line)
            if match:
                nodes.append(match.group(1))
    return nodes


def read_interceptor_symbols(path):
    """Returns the set of HIP entry points already defined by hip_intercept.c."""
    with open(path) as f:
        source = f.read()
    names = set(re.findall(r"FWD\d\(\s*[^,]+,\s*(\w+)", source))
    names.update(
        re.findall(r"^[A-Za-z_][\w \t\*]*?[\s\*](\w+)\s*\(", source, re.M)
    )
    return names


def split_top_level(text):
    """Splits a parameter list on commas that are not nested in (), [] or {}."""
    parts = []
    depth = 0
    current = []
    for char in text:
        if char in "([{":
            depth += 1
        elif char in ")]}":
            depth -= 1
        if char == "," and depth == 0:
            parts.append("".join(current))
            current = []
        else:
            current.append(char)
    if current:
        parts.append("".join(current))
    return parts


def extract_signatures(binding_dir):
    """Returns {name: (return_type, parameter_list)} from the HIP binding.

    Definitions are preferred over declarations because they carry the exact
    spelling the binding compiles with; api.h covers entry points whose
    definition lives outside the scanned files.
    """
    signatures = {}
    definition = re.compile(r"\bHIPAPI\s+([A-Za-z_][\w \t\*]*?)\s+(\w+)\s*\(")
    for dirpath, _, filenames in os.walk(binding_dir):
        for filename in sorted(filenames):
            if not filename.endswith(".c"):
                continue
            path = os.path.join(dirpath, filename)
            with open(path, errors="ignore") as f:
                source = f.read()
            for match in definition.finditer(source):
                name = match.group(2)
                index = match.end() - 1
                depth = 0
                cursor = index
                while cursor < len(source):
                    if source[cursor] == "(":
                        depth += 1
                    elif source[cursor] == ")":
                        depth -= 1
                        if depth == 0:
                            break
                    cursor += 1
                if "{" not in source[cursor : cursor + 120]:
                    continue
                signatures.setdefault(
                    name, (match.group(1).strip(), source[index + 1 : cursor])
                )
    # Declarations in api.h fill in anything the definitions did not cover.
    with open(os.path.join(binding_dir, "api.h")) as f:
        header = f.read()
    for match in re.finditer(
        r"^HIPAPI\s+([A-Za-z_][\w \t\*]*?)\s+(\w+)\s*\(([^;]*)\)\s*;",
        header,
        re.M,
    ):
        signatures.setdefault(match.group(2), (match.group(1).strip(), match.group(3)))
    return signatures


def parameter_names(parameters):
    """Returns the parameter names to forward, or None if not derivable."""
    stripped = parameters.strip()
    if not stripped or stripped == "void":
        return []
    if "..." in stripped:
        return None  # Variadic entry points cannot be forwarded generically.
    names = []
    for part in split_top_level(stripped):
        part = part.strip()
        if not part:
            continue
        pointer = re.search(r"\(\s*\*\s*(\w+)\s*\)", part)
        if pointer:
            names.append(pointer.group(1))
            continue
        trailing = re.search(r"(\w+)\s*(\[[^\]]*\])?\s*$", part)
        if trailing and trailing.group(1) not in TYPE_WORDS:
            names.append(trailing.group(1))
            continue
        return None
    return names


def default_expression(return_type):
    """Returns a zero value initializer that is valid for the return type."""
    if return_type.endswith("*"):
        return "NULL"
    if re.match(r"^(void|bool|char|short|int|long|float|double|size_t|"
                r"ssize_t|u?int\d+_t|hip\w+_t|enum\s+\w+)$", return_type):
        return "0"
    return "{0}"


def extract_compat_types(path):
    """Returns the local compatibility declarations block from abi_stubs.c.

    api.h does not describe the legacy ABI entry points, so their parameter
    types live next to their definitions. Copying the block into the generated
    file keeps both in sync with a single source.
    """
    with open(path) as f:
        lines = f.readlines()
    start = None
    for index, line in enumerate(lines):
        if line.startswith(COMPAT_MARKER):
            start = index
            break
    if start is None:
        sys.exit("error: %s no longer contains %r" % (path, COMPAT_MARKER))
    end = start
    while end < len(lines) and not lines[end].startswith("#define"):
        end += 1
    return "".join(lines[start:end]).rstrip() + "\n"


def find_type_definition(binding_dir, name):
    """Returns the definition text of a binding-private type, or None."""
    patterns = [
        re.compile(r"typedef\s+struct\s+" + re.escape(name) + r"\s*\{"),
        re.compile(r"typedef\s+union\s+" + re.escape(name) + r"\s*\{"),
        re.compile(r"typedef\s+enum\s+" + re.escape(name) + r"\s*\{"),
        re.compile(r"typedef\s+[^;{}]*\b" + re.escape(name) + r"\s*;"),
    ]
    for dirpath, _, filenames in os.walk(binding_dir):
        for filename in sorted(filenames):
            if not filename.endswith((".c", ".h")):
                continue
            path = os.path.join(dirpath, filename)
            with open(path, errors="ignore") as f:
                source = f.read()
            for pattern in patterns:
                match = pattern.search(source)
                if not match:
                    continue
                if "{" not in match.group(0):
                    return match.group(0)
                brace = source.index("{", match.start())
                depth = 0
                cursor = brace
                while cursor < len(source):
                    if source[cursor] == "{":
                        depth += 1
                    elif source[cursor] == "}":
                        depth -= 1
                        if depth == 0:
                            break
                    cursor += 1
                semicolon = source.index(";", cursor)
                return source[match.start() : semicolon + 1]
    return None


def needs_private_types(signatures, generated, api_text, compat_text):
    """Returns private type names the generated signatures refer to."""
    known = set(re.findall(r"[A-Za-z_]\w*", api_text))
    known.update(re.findall(r"[A-Za-z_]\w*", compat_text))
    known.update(TYPE_WORDS)
    needed = []
    seen = set()
    for name in generated:
        return_type, parameters = signatures[name]
        text = return_type + " " + parameter_types(parameters)
        for token in re.findall(r"[A-Za-z_]\w*", text):
            if token not in known and token not in seen:
                seen.add(token)
                needed.append(token)
    return needed


def emit_c(exports, generated, signatures, source_of, compat_types, private_types):
    lines = [HEADER % {"count": len(generated), "compat": compat_types + private_types}]
    for name in generated:
        return_type, parameters = signatures[name]
        names = parameter_names(parameters)
        node = exports[name]
        lines.append("// %s@%s (from %s)\n" % (name, node, source_of[name]))
        lines.append("HIPAPI %s %s(%s) {\n" % (return_type, name, parameters.strip()))
        lines.append("  typedef %s (*pfn_%s_t)(%s);\n" % (
            return_type, name, parameter_types(parameters)))
        lines.append("  static pfn_%s_t hip_stub_fn = NULL;\n" % name)
        lines.append("  if (!hip_stub_fn) {\n")
        lines.append('    hip_stub_fn = (pfn_%s_t)dlsym(hip_passthrough_backend_lib(), "%s");\n'
                     % (name, name))
        lines.append("  }\n")
        call = "hip_stub_fn(%s)" % ", ".join(names)
        if return_type == "void":
            lines.append("  if (hip_stub_fn) %s;\n" % call)
        else:
            lines.append("  %s _ret = %s;\n" % (return_type, default_expression(return_type)))
            lines.append("  if (hip_stub_fn) _ret = %s;\n" % call)
        lines.append('  hip_passthrough_log_call("%s");\n' % name)
        if return_type != "void":
            lines.append("  return _ret;\n")
        lines.append("}\n\n")
    return "".join(lines)


def parameter_types(parameters):
    """Returns the parameter list with every parameter name removed."""
    stripped = parameters.strip()
    if not stripped or stripped == "void":
        return "void"
    types = []
    for part in split_top_level(stripped):
        part = part.strip()
        if not part:
            continue
        pointer = re.search(r"\(\s*\*\s*(\w+)\s*\)", part)
        if pointer:
            types.append(part[: pointer.start(1)] + part[pointer.end(1) :])
            continue
        trailing = re.search(r"(\w+)\s*(\[[^\]]*\])?\s*$", part)
        types.append(part[: trailing.start(1)] + part[trailing.end(1) :])
    return ", ".join(t.strip() for t in types)


def emit_map(exports, nodes):
    extra = defaultdict(list)
    for name in INTERCEPTOR_EXPORTS:
        extra[nodes[0]].append(name)
    by_node = defaultdict(list)
    for name, node in exports.items():
        by_node[node].append(name)
    for node in nodes:
        by_node[node].extend(extra[node])
    lines = [
        "# Auto-generated by libhrx/src/passthrough/generate_stubs.py -- DO NOT EDIT.\n",
        "# Symbol versions must match libhrx/src/binding/hip/amdhip64.map so that\n",
        "# versioned HIP calls resolve to the interceptor.\n\n",
    ]
    for index, node in enumerate(nodes):
        lines.append("%s {\n  global:\n" % node)
        for name in sorted(by_node[node]):
            lines.append("    %s;\n" % name)
        if index == len(nodes) - 1:
            lines.append("  local:\n    *;\n")
        lines.append("};\n\n")
    return "".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--reference-lib",
        required=True,
        help="libamdhip64.so whose export table defines the required surface",
    )
    parser.add_argument("--check", action="store_true",
                        help="verify the generated files are up to date")
    args = parser.parse_args()

    if not os.path.exists(args.reference_lib):
        sys.exit("error: reference library not found: %s" % args.reference_lib)

    exports = read_exports(args.reference_lib)
    map_nodes = read_map_nodes(AMD_MAP)
    reference_nodes = list(OrderedDict.fromkeys(exports.values()))

    missing_nodes = sorted(set(map_nodes) - set(reference_nodes))
    extra_nodes = sorted(set(reference_nodes) - set(map_nodes))
    if missing_nodes or extra_nodes:
        sys.exit(
            "error: version nodes differ from amdhip64.map\n"
            "  in amdhip64.map but not in the reference library: %s\n"
            "  in the reference library but not in amdhip64.map: %s"
            % (", ".join(missing_nodes) or "(none)", ", ".join(extra_nodes) or "(none)")
        )

    intercept_path = os.path.join(PASSTHROUGH_DIR, "hip_intercept.c")
    provided = read_interceptor_symbols(intercept_path)
    signatures = extract_signatures(BINDING_DIR)

    generated = []
    unsupported = []
    for name in sorted(exports):
        if name in provided:
            continue
        if name not in signatures:
            unsupported.append((name, "no signature found in the HIP binding"))
            continue
        if parameter_names(signatures[name][1]) is None:
            unsupported.append((name, "variadic or unparseable parameter list"))
            continue
        if set(parameter_names(signatures[name][1])) & {"hip_stub_fn", "_ret"}:
            unsupported.append((name, "parameter collides with a generated local"))
            continue
        generated.append(name)

    covered = set(provided) | set(generated)
    uncovered = sorted(set(exports) - covered)
    if unsupported or uncovered:
        for name, reason in unsupported:
            print("unsupported: %s (%s)" % (name, reason), file=sys.stderr)
        for name in uncovered:
            print("uncovered: %s" % name, file=sys.stderr)
        sys.exit(
            "error: %d reference symbols have no forwarder; add them to "
            "hip_intercept.c or teach the generator their signature"
            % len(set(exports) - covered)
        )

    source_of = {}
    for dirpath, _, filenames in os.walk(BINDING_DIR):
        for filename in filenames:
            if filename.endswith(".c"):
                path = os.path.join(dirpath, filename)
                with open(path, errors="ignore") as f:
                    text = f.read()
                for name in generated:
                    if re.search(r"\bHIPAPI\b[^;{]*\b%s\s*\(" % re.escape(name), text):
                        source_of.setdefault(name, os.path.relpath(path, REPO_ROOT))

    compat_types = extract_compat_types(os.path.join(BINDING_DIR, "abi_stubs.c"))
    with open(os.path.join(BINDING_DIR, "api.h")) as f:
        api_text = f.read()
    private = []
    for type_name in needs_private_types(signatures, generated, api_text, compat_types):
        definition = find_type_definition(BINDING_DIR, type_name)
        if definition is None:
            sys.exit(
                "error: %s is used by a generated forwarder but no definition was "
                "found in %s; teach generate_stubs.py about it"
                % (type_name, os.path.relpath(BINDING_DIR, REPO_ROOT))
            )
        private.append(definition)
    private_types = "\n\n".join(private) + ("\n" if private else "")

    c_text = emit_c(
        exports, generated, signatures, source_of, compat_types, private_types
    )
    map_text = emit_map(exports, map_nodes)

    if args.check:
        ok = True
        for path, text in ((C_OUT, c_text), (MAP_OUT, map_text)):
            if not os.path.exists(path) or open(path).read() != text:
                print("out of date: %s" % path, file=sys.stderr)
                ok = False
        if not ok:
            sys.exit("error: generated files are stale; re-run this generator")
        print("up to date: %d reference symbols, %d generated forwarders"
              % (len(exports), len(generated)))
        return

    with open(C_OUT, "w") as f:
        f.write(c_text)
    with open(MAP_OUT, "w") as f:
        f.write(map_text)
    print("wrote %s (%d forwarders)" % (os.path.relpath(C_OUT, REPO_ROOT), len(generated)))
    print("wrote %s (%d version nodes, %d symbols)"
          % (os.path.relpath(MAP_OUT, REPO_ROOT), len(map_nodes), len(exports)))


if __name__ == "__main__":
    main()
